import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import { parse } from "@babel/parser";
const source = readFileSync(new URL("./src/App.jsx", import.meta.url), "utf8");
class ImportDate extends Date { constructor(...args) { super(...(args.length ? args : [2026, 9, 6, 12])); } }
const context = vm.createContext({ console, Date: ImportDate });
const ast = parse(source, { sourceType: "module", plugins: ["jsx"] });
vm.runInContext(ast.program.body.filter((node) => node.type === "FunctionDeclaration" && node.start >= source.indexOf("function toNumber(")).map((node) => source.slice(node.start, node.end)).join("\n"), context);
const { getDocument } = await import("pdfjs-dist/legacy/build/pdf.mjs");
const task = getDocument({ data: new Uint8Array(readFileSync(new URL("../bank/TataMotorsFinance_8000136684_Repayment_Schedule.pdf", import.meta.url))) });
const document = await task.promise;
const text = await context.extractPdfNativeText(document);
const parsed = context.normalizePdfFinanceRow(context.parseBankPdfText(text, "TataMotorsFinance_8000136684_Repayment_Schedule.pdf"));
assert.equal(parsed.owner, "AMIT SINGHAL");
assert.equal(parsed.financier, "TATA MOTORS FINANCE SOLUTIONS LTD");
assert.equal(parsed.loanAccount, "8000136684");
assert.equal(parsed.regNo, "GJ06YY6199");
assert.equal(Number(parsed.loanAmount), 950000);
assert.equal(Number(parsed.emiAmount), 35790);
assert.equal(Number(parsed.interestRate), 15.4486);
assert.equal(parsed.emiStart, "15-09-2021");
assert.equal(parsed.emiEnd, "15-05-2024");
assert.equal(Number(parsed.tenure), 33);
assert.equal(Number(parsed.paidEmi), 33);
assert.equal(Number(parsed.bankClosingPrincipal), 0);
assert.equal(parsed.financeStatus, "CLOSED");
assert.equal(parsed.emiSchedule.length, 33);
assert.equal(Number(parsed.bankClosingPrincipal), 0);
assert.equal(parsed.emiSchedule.at(-1).status, "Paid");
await task.destroy();
console.log("Tata Motors repayment schedule parser passed");
